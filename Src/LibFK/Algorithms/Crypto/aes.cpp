static const uint32_t RCON[11] = {
    0,0x01000000,0x02000000,0x04000000,0x08000000,0x10000000,
    0x20000000,0x40000000,0x80000000,0x1b000000,0x36000000
};

static uint8_t xtime(uint8_t a) {
    return (uint8_t)((a << 1) ^ (a & 0x80 ? 0x1b : 0));
}

static uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t r = 0;
    for (int i = 0; i < 8; ++i) {
        if (b & 1) r ^= a;
        a = xtime(a); b >>= 1;
    }
    return r;
}

static uint32_t subword(uint32_t w) {
    return (uint32_t)SBOX[w >> 24] << 24 | (uint32_t)SBOX[(w >> 16) & 0xff] << 16 |
           (uint32_t)SBOX[(w >> 8)  & 0xff] << 8  | SBOX[w & 0xff];
}

static uint32_t rotword(uint32_t w) { return (w << 8) | (w >> 24); }

void aes256_key_expand(const uint8_t key[AES256_KEY_SIZE], Aes256Key* out) {
    uint32_t* rk = out->rk;
    for (int i = 0; i < 8; ++i)
        rk[i] = (uint32_t)key[i*4] << 24 | (uint32_t)key[i*4+1] << 16 |
                (uint32_t)key[i*4+2] << 8 | key[i*4+3];
    for (int i = 8; i < 60; ++i) {
        uint32_t t = rk[i-1];
        if (i % 8 == 0)      t = subword(rotword(t)) ^ RCON[i/8];
        else if (i % 8 == 4) t = subword(t);
        rk[i] = rk[i-8] ^ t;
    }
}

static void state_xor(uint8_t s[16], const uint32_t* rk) {
    for (int c = 0; c < 4; ++c) {
        s[c*4+0] ^= rk[c] >> 24; s[c*4+1] ^= (rk[c] >> 16) & 0xff;
        s[c*4+2] ^= (rk[c] >> 8) & 0xff; s[c*4+3] ^= rk[c] & 0xff;
    }
}

// AES in column-major order (word = one column)
static void sub_shift_mix(uint8_t s[16], bool mix) {
    uint8_t t[16];
    // SubBytes + ShiftRows
    t[ 0] = SBOX[s[ 0]]; t[ 1] = SBOX[s[ 5]]; t[ 2] = SBOX[s[10]]; t[ 3] = SBOX[s[15]];
    t[ 4] = SBOX[s[ 4]]; t[ 5] = SBOX[s[ 9]]; t[ 6] = SBOX[s[14]]; t[ 7] = SBOX[s[ 3]];
    t[ 8] = SBOX[s[ 8]]; t[ 9] = SBOX[s[13]]; t[10] = SBOX[s[ 2]]; t[11] = SBOX[s[ 7]];
    t[12] = SBOX[s[12]]; t[13] = SBOX[s[ 1]]; t[14] = SBOX[s[ 6]]; t[15] = SBOX[s[11]];
    if (!mix) { fk::memory::copy(s, t, 16); return; }
    // MixColumns
    for (int c = 0; c < 4; ++c) {
        uint8_t a = t[c*4], b = t[c*4+1], d = t[c*4+2], e = t[c*4+3];
        s[c*4+0] = gmul(2,a) ^ gmul(3,b) ^ d ^ e;
        s[c*4+1] = a ^ gmul(2,b) ^ gmul(3,d) ^ e;
        s[c*4+2] = a ^ b ^ gmul(2,d) ^ gmul(3,e);
        s[c*4+3] = gmul(3,a) ^ b ^ d ^ gmul(2,e);
    }
}

static void inv_shift_sub(uint8_t s[16]) {
    uint8_t t[16];
    // InvShiftRows + InvSubBytes
    t[ 0] = INV_SBOX[s[ 0]]; t[ 1] = INV_SBOX[s[13]]; t[ 2] = INV_SBOX[s[10]]; t[ 3] = INV_SBOX[s[ 7]];
    t[ 4] = INV_SBOX[s[ 4]]; t[ 5] = INV_SBOX[s[ 1]]; t[ 6] = INV_SBOX[s[14]]; t[ 7] = INV_SBOX[s[11]];
    t[ 8] = INV_SBOX[s[ 8]]; t[ 9] = INV_SBOX[s[ 5]]; t[10] = INV_SBOX[s[ 2]]; t[11] = INV_SBOX[s[15]];
    t[12] = INV_SBOX[s[12]]; t[13] = INV_SBOX[s[ 9]]; t[14] = INV_SBOX[s[ 6]]; t[15] = INV_SBOX[s[ 3]];
    fk::memory::copy(s, t, 16);
}

static void inv_mix(uint8_t s[16]) {
    uint8_t t[16];
    for (int c = 0; c < 4; ++c) {
        uint8_t a = s[c*4], b = s[c*4+1], d = s[c*4+2], e = s[c*4+3];
        t[c*4+0] = gmul(0xe,a) ^ gmul(0xb,b) ^ gmul(0xd,d) ^ gmul(0x9,e);
        t[c*4+1] = gmul(0x9,a) ^ gmul(0xe,b) ^ gmul(0xb,d) ^ gmul(0xd,e);
        t[c*4+2] = gmul(0xd,a) ^ gmul(0x9,b) ^ gmul(0xe,d) ^ gmul(0xb,e);
        t[c*4+3] = gmul(0xb,a) ^ gmul(0xd,b) ^ gmul(0x9,d) ^ gmul(0xe,e);
    }
    fk::memory::copy(s, t, 16);
}

void aes256_encrypt(const Aes256Key* k, const uint8_t in[16], uint8_t out[16]) {
    uint8_t s[16];
    fk::memory::copy(s, in, 16);
    state_xor(s, k->rk);
    for (size_t r = 1; r < AES256_ROUNDS; ++r) {
        sub_shift_mix(s, true);
        state_xor(s, k->rk + r * 4);
    }
    sub_shift_mix(s, false);
    state_xor(s, k->rk + AES256_ROUNDS * 4);
    fk::memory::copy(out, s, 16);
}

void aes256_decrypt(const Aes256Key* k, const uint8_t in[16], uint8_t out[16]) {
    uint8_t s[16];
    fk::memory::copy(s, in, 16);
    state_xor(s, k->rk + AES256_ROUNDS * 4);
    for (size_t r = AES256_ROUNDS - 1; r >= 1; --r) {
        inv_shift_sub(s);
        state_xor(s, k->rk + r * 4);
        inv_mix(s);
    }
    inv_shift_sub(s);
    state_xor(s, k->rk);
    fk::memory::copy(out, s, 16);
}

