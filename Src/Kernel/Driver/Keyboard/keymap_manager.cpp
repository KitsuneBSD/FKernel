KeymapManager& KeymapManager::the() {
    static KeymapManager instance;
    return instance;
}

char KeymapManager::translate(uint8_t keycode, bool shift, bool alt) const {
    if (keycode >= 128)
        return 0;

    // Special combination: Alt + Q -> /
    if (alt && keycode == 0x10) {
        return '/';
    }

    if (m_current_layout == KeyboardLayout::ABNT2) {
        return shift ? abnt2_set1_shift[keycode] : abnt2_set1[keycode];
    }
    
    return shift ? us_set1_shift[keycode] : us_set1[keycode];
}

